import SwiftUI

enum AppColor {
    static let accentContrast: Color = .primitiveAccentContrast
    static let accentPrimary: Color = .primitiveAccentPrimary
    static let accentSecondary: Color = .primitiveAccentSecondary
    static let accentTertiary: Color = .primitiveAccentTertiary
    static let accentQuaternary: Color = .primitiveAccentQuaternary
    static let disabledBackground: Color = .primitiveDisabledBackground
    static let destructive: Color = .primitiveDestructive
    static let disabledForeground: Color = .primitiveDisabledForeground
    static let fieldBackground: Color = .primitiveFieldBackground
    static let fieldBorder: Color = .primitiveFieldBorder
    static let imageBorder: Color = .primitiveImageBorder
    static let searchbarBackground: Color = .primitiveSearchbarBackground
    static let searchbarBorder: Color = .primitiveSearchbarBorder
    static let success: Color = .primitiveSuccess
    static let surface: Color = .primitiveSurface
    
    enum Page {
        static let background: Color = .primitiveBackground
    }
    
    enum Label {
        static let title: Color = .labelTitle
        static let primary: Color = .labelPrimary
        static let secondary: Color = .labelSecondary
    }
}
